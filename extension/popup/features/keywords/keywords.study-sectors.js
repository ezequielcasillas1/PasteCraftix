function keywordEntries(rows) {
  return Object.freeze((rows || []).map(([title, aliases]) => Object.freeze({
    title,
    aliases: Object.freeze((aliases || []).map((alias) => String(alias))),
  })));
}

function sectorEntries(pairs, keywordMap = null) {
  return Object.freeze(pairs.map(([title, aliases]) => Object.freeze({
    title,
    aliases: Object.freeze(aliases.map((alias) => String(alias))),
    keywords: keywordEntries(keywordMap?.[title]),
  })));
}

function statePairs() {
  return CONTINUING_EDUCATION_STATES.map(([state, title]) => stateSector(title, state, stateExtras(state)));
}

