function aliasKey(value) {
  return String(value || '').trim().toLowerCase().replace(/\s+/g, ' ');
}

function buildAliases(sectors) {
  const map = Object.create(null);
  for (const [title, aliases] of sectors) {
    for (const alias of aliases) {
      const key = aliasKey(alias);
      if (!key || Object.prototype.hasOwnProperty.call(map, key)) continue;
      map[key] = title;
    }
  }
  return Object.freeze(map);
}

function stateSector(title, state, extras = []) {
  const name = state.toLowerCase();
  return [title, [
    title,
    `${name} continuing education`,
    `continuing education ${name}`,
    `${name} community college`,
    `${name} community colleges`,
    `${name} workforce training`,
    `${name} adult education`,
    ...extras,
  ]];
}

