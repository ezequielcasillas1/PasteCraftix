#!/usr/bin/env node
/**
 * Regenerate the shipped Mini Games catalog from Sable/Rio's JSON export.
 *
 *   npm run games:catalog -- /path/to/mini-games-catalog.json
 *   (default source: /workspace/sable/pastecraft/mini-games-catalog-2026-10-27.json)
 *
 * Writes extension/popup/features/keywords/keywords.games.catalog.js. Ids are slugified
 * from names (collisions get -2, -3…), group labels map to group ids, and every row is run
 * through the same validator the popup uses, so the build fails loudly on bad data.
 * Sample entries are never written.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = process.argv[2] || '/workspace/sable/pastecraft/mini-games-catalog-2026-10-27.json';
const out = path.join(here, '../extension/popup/features/keywords/keywords.games.catalog.js');
// keywords.games.js imports the generated module; make sure one exists before loading the validator.
if (!fs.existsSync(out)) fs.writeFileSync(out, 'export const GAMES_CATALOG_DATA = [];\n');
const { GAME_GROUPS, normalizeGame } = await import('../extension/popup/features/keywords/keywords.games.js');

export function slugify(name) {
  return String(name || '').normalize('NFKD').replace(/[\u0300-\u036f]/g, '')
    .toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

const groupIds = new Map();
GAME_GROUPS.forEach((g) => {
  groupIds.set(g.id, g.id);
  groupIds.set(g.label.toLowerCase(), g.id);
});

const raw = JSON.parse(fs.readFileSync(source, 'utf8'));
if (!Array.isArray(raw)) throw new Error('Catalog must be a JSON array');
const used = new Set();
const errors = [];
const games = [];
raw.forEach((row, i) => {
  if (row?.sample === true) return;
  const group = groupIds.get(String(row?.group || '').trim().toLowerCase());
  let id = slugify(row?.name);
  for (let n = 2; used.has(id); n += 1) id = `${slugify(row?.name)}-${n}`;
  const game = normalizeGame({ ...row, id, group, sample: false });
  if (!game) { errors.push(`#${i} ${JSON.stringify(row?.name)}: bad name or group ${JSON.stringify(row?.group)}`); return; }
  if (!game.howToPlay.length) errors.push(`#${i} ${game.name}: howToPlay missing or not 3-5 steps (section will be hidden)`);
  used.add(id);
  const { sample, ...plain } = game;
  games.push({ ...plain, keywords: [...plain.keywords], howToPlay: [...plain.howToPlay] });
});

const header = `// GENERATED by scripts/build-games-catalog.mjs from ${path.basename(source)} — do not edit by hand.\n`
  + `// ${games.length} games. Regenerate with: npm run games:catalog -- <path-to-json>\n`;
fs.writeFileSync(out, `${header}export const GAMES_CATALOG_DATA = ${JSON.stringify(games, null, 2)};\n`);
console.log(`Wrote ${games.length} games to ${path.relative(process.cwd(), out)}`);
if (errors.length) {
  console.warn(`${errors.length} warning(s):\n  ${errors.join('\n  ')}`);
  if (errors.some((e) => e.includes('bad name or group'))) process.exitCode = 1;
}
